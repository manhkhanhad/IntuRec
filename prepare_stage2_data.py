#!/usr/bin/env python3
"""Create and enrich the JSON datasets used by IntuRec stage 2.

This is a command-line replacement for ``preparedata2f2.ipynb``. It copies
the stage-1 CSV rows into ``*_extra/extra.json`` and adds the intuition lists
and scores generated by ``genf1midres.py``.
"""

import argparse
import json
import os
import random
import tempfile
from pathlib import Path
from typing import Any

import pandas as pd
import torch


SPLITS = ("train", "valid", "test")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset",
        required=True,
        help="Dataset directory name, for example CDs_and_Vinyl.",
    )
    parser.add_argument(
        "--source-data-root",
        type=Path,
        required=True,
        help="Root containing <dataset>/{train,valid,test}/*.csv.",
    )
    parser.add_argument(
        "--output-data-root",
        type=Path,
        default=Path("data"),
        help="Root containing beam files and receiving *_extra directories (default: data).",
    )
    parser.add_argument(
        "--beam-num",
        type=int,
        default=15,
        help="Number of intuition items to retain (default: 15).",
    )
    parser.add_argument(
        "--balance-ratio",
        type=float,
        default=None,
        help=(
            "Probability of retaining the target in training intuitions. "
            "By default, use test_hit/train_hit as in the notebook."
        ),
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=0,
        help="Random seed for training-set balancing (default: 0).",
    )
    return parser.parse_args()


def find_source_csv(source_root: Path, dataset: str, split: str) -> Path:
    split_dir = source_root / dataset / split
    matches = sorted(split_dir.glob(f"{dataset}*.csv"))
    if len(matches) != 1:
        raise FileNotFoundError(
            f"Expected exactly one {dataset}*.csv in {split_dir}, found {len(matches)}"
        )
    return matches[0]


def load_beam_result(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(f"Missing beam result: {path}")

    # The files are produced locally by genf1midres.py and contain strings,
    # lists, and tensors, so they require the general PyTorch loader.
    result = torch.load(path, map_location="cpu", weights_only=False)
    if not isinstance(result, dict) or "outputs" not in result or "scores" not in result:
        raise ValueError(f"{path} must contain 'outputs' and 'scores'")
    return result


def write_json_atomic(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".tmp",
            delete=False,
        ) as temp_file:
            json.dump(records, temp_file, indent=4)
            temp_file.write("\n")
            temp_path = Path(temp_file.name)
        os.replace(temp_path, path)
    finally:
        if temp_path is not None and temp_path.exists():
            temp_path.unlink()


def load_base_records(
    source_root: Path, output_root: Path, dataset: str, split: str
) -> list[dict[str, Any]]:
    existing_path = output_root / dataset / f"{split}_extra" / "extra.json"
    if existing_path.is_file():
        with existing_path.open(encoding="utf-8") as input_file:
            records = json.load(input_file)
        if not isinstance(records, list):
            raise ValueError(f"{existing_path} must contain a JSON list")
        return records

    csv_path = find_source_csv(source_root, dataset, split)
    # Converting through JSON matches pandas.DataFrame.to_json(...,
    # orient="records") in data_process.ipynb, including null handling.
    frame = pd.read_csv(csv_path)
    return json.loads(frame.to_json(orient="records"))


def target_hit_rate(records: list[dict[str, Any]], outputs: list[list[str]]) -> float:
    if len(records) != len(outputs):
        raise ValueError(
            f"Data/beam row-count mismatch: {len(records)} records versus {len(outputs)} outputs"
        )
    if not records:
        raise ValueError("Cannot calculate a hit rate for an empty split")

    hit_count = sum(
        f'"{row["item_title"]}"' in row_outputs
        for row, row_outputs in zip(records, outputs)
    )
    return hit_count / len(records)


def enrich_split(
    records: list[dict[str, Any]],
    result: dict[str, Any],
    split: str,
    beam_num: int,
    balance_ratio: float,
    rng: random.Random,
) -> None:
    outputs = result["outputs"]
    scores = result["scores"]
    if len(records) != len(outputs) or len(records) != len(scores):
        raise ValueError(
            f"{split}: {len(records)} records, {len(outputs)} output rows, "
            f"and {len(scores)} score rows must match"
        )

    for row_number, (row, row_outputs, row_scores) in enumerate(
        zip(records, outputs, scores), start=1
    ):
        if len(row_outputs) != len(row_scores):
            raise ValueError(
                f"{split} row {row_number}: {len(row_outputs)} outputs but "
                f"{len(row_scores)} scores"
            )

        target = f'"{row["item_title"]}"'
        filtered_outputs: list[str] = []
        filtered_scores: list[Any] = []
        target_index = -1

        for output, score in zip(row_outputs, row_scores):
            if output != target:
                filtered_outputs.append(output)
                filtered_scores.append(score)
            elif split != "train" or rng.random() < balance_ratio:
                target_index = len(filtered_outputs)
                filtered_outputs.append(output)
                filtered_scores.append(score)

        if split == "train" and len(filtered_outputs) == beam_num + 1:
            removable_indices = [
                index for index in range(len(filtered_outputs)) if index != target_index
            ]
            remove_index = rng.choice(removable_indices)
            filtered_outputs.pop(remove_index)
            filtered_scores.pop(remove_index)

        if len(filtered_outputs) != beam_num:
            raise ValueError(
                f"{split} row {row_number}: expected {beam_num} filtered outputs, "
                f"got {len(filtered_outputs)}"
            )

        row[f"intuition_list_{beam_num}"] = filtered_outputs
        row[f"intuition_scores_{beam_num}"] = filtered_scores


def main() -> None:
    args = parse_args()
    if args.beam_num < 1:
        raise ValueError("--beam-num must be positive")
    if args.balance_ratio is not None and not 0.0 <= args.balance_ratio <= 1.0:
        raise ValueError("--balance-ratio must be between 0 and 1")

    dataset_dir = args.output_data_root / args.dataset
    records: dict[str, list[dict[str, Any]]] = {}
    results: dict[str, dict[str, Any]] = {}

    for split in SPLITS:
        records[split] = load_base_records(
            args.source_data_root, args.output_data_root, args.dataset, split
        )
        generated_beams = args.beam_num + 1 if split == "train" else args.beam_num
        beam_path = dataset_dir / f"{split}_beam_{generated_beams}.pt"
        results[split] = load_beam_result(beam_path)

    hit_rates = {
        split: target_hit_rate(records[split], results[split]["outputs"])
        for split in SPLITS
    }
    if args.balance_ratio is None:
        if hit_rates["train"] == 0:
            raise ValueError(
                "Training target hit rate is zero; pass --balance-ratio explicitly"
            )
        balance_ratio = hit_rates["test"] / hit_rates["train"]
        if not 0.0 <= balance_ratio <= 1.0:
            raise ValueError(
                f"Calculated balance ratio {balance_ratio:.6f} is outside [0, 1]; "
                "pass --balance-ratio explicitly"
            )
    else:
        balance_ratio = args.balance_ratio

    print("Target hit rates:")
    for split in SPLITS:
        print(f"  {split}: {hit_rates[split]:.6f}")
    print(f"Training balance ratio: {balance_ratio:.6f}")

    rng = random.Random(args.seed)
    for split in SPLITS:
        enrich_split(
            records[split],
            results[split],
            split,
            args.beam_num,
            balance_ratio,
            rng,
        )

    for split in SPLITS:
        output_path = dataset_dir / f"{split}_extra" / "extra.json"
        write_json_atomic(output_path, records[split])
        print(f"Wrote {len(records[split])} rows to {output_path}")


if __name__ == "__main__":
    main()
